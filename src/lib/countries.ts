const PROFILE_COUNTRY_SET = new Set<string>(PROFILE_COUNTRY_CODES);

export type ProfileCountryCode = (typeof PROFILE_COUNTRY_CODES)[number];

export function isProfileCountryCode(value: string): value is ProfileCountryCode {
  return PROFILE_COUNTRY_SET.has(value);
}

export function profileCountryLabel(code: string, locale: string): string {
  const normalized = code.trim().toUpperCase();
  if (!normalized || !isProfileCountryCode(normalized)) return "";
  try {
    return new Intl.DisplayNames([locale], { type: "region" }).of(normalized) ?? normalized;
  } catch {
    return normalized;
  }
}

export function profileCountryOptions(locale: string): { code: ProfileCountryCode; label: string }[] {
  const display = (() => {
    try {
      return new Intl.DisplayNames([locale], { type: "region" });
    } catch {
      return null;
    }
  })();

  const options = PROFILE_COUNTRY_CODES.map((code) => ({
    code,
    label: display?.of(code) ?? code,
  }));

  options.sort((a, b) => a.label.localeCompare(b.label, locale, { sensitivity: "base" }));

  const vnIndex = options.findIndex((row) => row.code === "VN");
  if (vnIndex > 0) {
    const [vn] = options.splice(vnIndex, 1);
    options.unshift(vn);
  }

  return options;
}

export function formatProfileAddress(
  address: string,
  countryCode: string,
  locale: string,
): string {
  const line = address.trim();
  const country = profileCountryLabel(countryCode, locale);
  if (line && country) return `${line}\n${country}`;
  return line || country;
}
